from __future__ import annotations
import json
import os
from huggingface_hub import HfApi, create_repo


DATASET_CARD = """---
license: apache-2.0
task_categories:
  - text-generation
language:
  - en
tags:
  - reasoning
  - math
  - reasoning-effort
  - qwen
size_categories:
  - 1K<n<10K
---

# Sherry Reasoning Effort Dataset (0.1)

Math reasoning traces at 3 effort levels (low, medium, high) generated by **Qwen3.6-35B-A3B (NVFP4)** via API.

## Description

Each problem was sampled from NuminaMath-CoT (numeric-answer problems only, proofs filtered out).
For every problem, {n_candidates} candidates were sampled from the generator model with thinking enabled,
verified against the ground truth, and the 3 verified traces with different reasoning depths were kept:
the shortest labeled `low`, the median `medium`, and the longest `high`.

## Source

- Problems: [AI-MO/NuminaMath-CoT](https://huggingface.co/datasets/AI-MO/NuminaMath-CoT) (Apache-2.0)
- Generator: unsloth/Qwen3.6-35B-A3B-NVFP4-Fast (OpenAI-compatible API)
- Verification: exact-match/numeric on \\boxed{{}} against NuminaMath ground truth (all traces correct)

## Format

Each row is a JSON object:
- `problem`: the math problem text
- `source`: NuminaMath source (olympiads, synthetic_math, cn_k12, orca_math)
- `effort`: one of "low", "medium", "high" (assigned from observed reasoning depth)
- `thinking`: the reasoning content (separated from response)
- `thinking_tokens`: actual reasoning tokens reported by the API
- `response`: the final response (contains \\boxed{{}})
- `predicted_answer`: extracted answer from response
- `ground_truth`: extracted answer from NuminaMath solution
- `correct`: whether predicted matches ground truth (always true)
- `finish_reason`: API finish reason (always "stop"; truncated candidates discarded)
- `requested_effort`: prompt used for candidate generation (uniform "medium")

## Intended Use

SFT training for reasoning effort control in language models.
"""


def load_rows(jsonl_path: str) -> list[dict]:
    """Load all verified rows from a JSONL file."""
    rows = []
    with open(jsonl_path) as file:
        for line in file:
            row = json.loads(line)
            if isinstance(row, dict):
                rows.append(row)
    return rows


def upload_dataset(jsonl_path: str, repo_id: str, token: str = None):
    """Upload a JSONL dataset to HuggingFace Hub."""
    rows = load_rows(jsonl_path)
    n_candidates = max(len({row["problem"] for row in rows}) and 0, 0) or len(rows) // max(
        len({row["problem"] for row in rows}), 1
    )
    api = HfApi(token=token)

    create_repo(repo_id, repo_type="dataset", token=token, exist_ok=True)

    api.upload_file(
        path_or_fileobj=jsonl_path,
        path_in_repo="reasoning_effort_math.jsonl",
        repo_id=repo_id,
        repo_type="dataset",
        token=token,
    )

    card_path = "/tmp/dataset_card.md"
    with open(card_path, "w") as f:
        f.write(DATASET_CARD.format(n_candidates=n_candidates))
    api.upload_file(
        path_or_fileobj=card_path,
        path_in_repo="README.md",
        repo_id=repo_id,
        repo_type="dataset",
        token=token,
    )

    print(f"Uploaded {len(rows)} rows to https://huggingface.co/datasets/{repo_id}")


if __name__ == "__main__":
    import sys
    jsonl_path = sys.argv[1] if len(sys.argv) > 1 else "data/reasoning_effort_math.jsonl"
    repo_id = sys.argv[2] if len(sys.argv) > 2 else "valendra/sherry-reasoning-effort-0.1"
    token = os.environ.get("HF_TOKEN")
    upload_dataset(jsonl_path, repo_id, token)